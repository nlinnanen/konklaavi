"""Seed recent fact-checked claims from Google's Data Commons ClaimReview feed (CC BY).

A claim a fact-checker rated false, misleading or manipulated becomes an active narrative, and the
pages where the claim appeared become its fetch jobs. Only claims in HashTrust's domain are kept:
those reviewed by a European or Ukraine-focused fact-checker, or those about Russia, Ukraine, NATO,
the EU or migration. The feed comes from
https://storage.googleapis.com/datacommons-feeds/claimreview/latest/data.json

python -m app.seed.claimreview --file PATH [--since YYYY-MM-DD] [--limit N]
"""

