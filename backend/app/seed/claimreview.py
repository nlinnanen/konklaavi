        "lüge", "frei erfunden", "onwaar", "netočno", "невярно", "фалшив", "изфабрикуван", "фейк", "неправда",
        "hoaks", "نادرست", "شاخ", "خطأ", "خاطئ", "كاذب", "زائف", "مفبرك", "غير صحيح", "مش حقيقي", "誤り",
