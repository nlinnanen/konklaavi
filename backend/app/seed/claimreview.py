VERDICT_PREFIX = 40

log = logging.getLogger(__name__)


def feed_items(path: Path, chunk_size: int = 1 << 20) -> Iterator[dict]:
    """The ClaimReview items of a DataFeed file, decoded one feed element at a time."""
    decoder = json.JSONDecoder()
    with path.open(encoding="utf-8") as f:
        buffer = ""
        while (start := buffer.find('"dataFeedElement"')) < 0:
            chunk = f.read(chunk_size)
            if not chunk:
                return
            buffer = buffer[-32:] + chunk
        buffer = buffer[buffer.index("[", start) + 1 :]
        eof = False
        while True:
            buffer = buffer.lstrip().lstrip(",").lstrip()
            if buffer.startswith("]"):
                return
            try:
                element, end = decoder.raw_decode(buffer)
            except json.JSONDecodeError:
                if eof:
                    raise
                chunk = f.read(chunk_size)
                eof = not chunk
                buffer += chunk
                continue
            buffer = buffer[end:]
            items = element.get("item") if isinstance(element, dict) else None
            yield from (item for item in items or [] if isinstance(item, dict))


def published_on(item: dict) -> date | None:
    """The review's publication date, or None when missing or not a plausible date."""
    try:
        day = date.fromisoformat(str(item.get("datePublished", ""))[:10])
    except ValueError:
        return None
    return day if day.year >= 1990 else None


def _one(value: object) -> dict:
    if isinstance(value, list):
        value = value[0] if value else None
    return value if isinstance(value, dict) else {}


def _host(url: str) -> str:
    return (urlsplit(url).hostname or "").lower().removeprefix("www.")


def _on_host(host: str, hosts: Iterable[str]) -> bool:
    return any(host == h or host.endswith("." + h) for h in hosts)


def appearance_urls(item: dict) -> list[str]:
    """The fetchable URLs where the claim appeared, first appearance first, without duplicates."""
    reviewed = _one(item.get("itemReviewed"))
    appearances = reviewed.get("appearance") or []
    if isinstance(appearances, dict):
        appearances = [appearances]
    candidates = [reviewed.get("firstAppearance"), *appearances]
    own = _host(str(_one(item.get("author")).get("url") or item.get("url") or ""))
    urls = []
    for candidate in candidates:
        url = candidate.get("url") if isinstance(candidate, dict) else candidate
        if not isinstance(url, str) or urlsplit(url).scheme not in ("http", "https"):
            continue
        host = _host(url)
        archived = ARCHIVED.match(url)
        if archived and _on_host(_host(archived[1]), UNFETCHABLE_HOSTS):
            continue
        if not host or host == own or _on_host(host, UNFETCHABLE_HOSTS):
            continue
        if urlsplit(url).path.lower().endswith(MEDIA_SUFFIXES):
            continue
        urls.append(url.strip())
    return list(dict.fromkeys(urls))


def map_verdict(rating: str) -> str | None:
    """The negative verdict a rating name stands for, or None for a true, mixed or unrated claim."""
    head = rating.strip().lower().removeprefix("dw fact check:").strip()[:VERDICT_PREFIX]
    for verdict, keywords in VERDICT_KEYWORDS:
        if any(keyword in head for keyword in keywords):
            return verdict
    return None


def in_domain(item: dict) -> bool:
    """Whether a European or Ukraine-focused fact-checker reviewed the claim, or it is on the topic."""
    if _on_host(_host(str(_one(item.get("author")).get("url") or "")), FACT_CHECKER_HOSTS):
        return True
    text = str(item.get("claimReviewed", ""))
    return TOPIC.search(text) is not None or EU.search(text) is not None


@dataclass(frozen=True)
class Claim:
    claim: str
    fact_checker: str
    rating: str
    verdict: str
    review_url: str
    urls: list[str]


def select_claims(items: Iterable[dict], since: date) -> tuple[list[Claim], Counter]:
    """The claims to seed, and how many items are left after each filter."""
    funnel: Counter = Counter()
    claims = []
    seen = set()
    for item in items:
        funnel["items"] += 1
        day = published_on(item)
        if day is None or day < since or day > date.today():
            continue
        funnel["recent"] += 1
        text = str(item.get("claimReviewed") or "").strip()
        review_url = item.get("url")
        if not text or not isinstance(review_url, str) or review_url in seen:
            continue
        funnel["with claim"] += 1
        urls = appearance_urls(item)
        if not urls:
            continue
        funnel["fetchable appearance"] += 1
        rating = str(_one(item.get("reviewRating")).get("alternateName") or "").strip()
        verdict = map_verdict(rating)
        if verdict is None:
            continue
        funnel["negative verdict"] += 1
        if not in_domain(item):
            continue
        funnel["in domain"] += 1
        seen.add(review_url)
        author = _one(item.get("author"))
        fact_checker = str(author.get("name") or "").strip() or _host(str(author.get("url") or review_url))
        claims.append(Claim(text, fact_checker, rating, verdict, review_url, urls[:MAX_URLS]))
    return claims, funnel


@dataclass(frozen=True)
class ImportResult:
    narratives: int
    fetch_jobs: int


def import_claims(conn: Connection, claims: list[Claim]) -> ImportResult:
    """Create an active narrative and fetch jobs for its appearance URLs per claim not imported before."""
    conn.execute("SELECT pg_advisory_xact_lock(%s)", (_LOCK_KEY,))
    narratives = fetch_jobs = 0
    for claim in claims:
        exists = conn.execute(
            "SELECT 1 FROM narrative WHERE source = 'factcheck' AND source_url = %s", (claim.review_url,)
        ).fetchone()
        if exists:
            continue
        narrative_id = conn.execute(
            "INSERT INTO narrative (title, claim, explanation, verdict, source, source_url, state)"
            " VALUES (%s, %s, %s, %s, 'factcheck', %s, 'active') RETURNING id",
            (
                claim.claim,
                claim.claim,
                f"{claim.fact_checker}: {claim.rating}",
                claim.verdict,
                claim.review_url,
            ),
        ).fetchone()[0]
        narratives += 1
        for url in claim.urls:
            enqueue(conn, "fetch", {"url": url, "reason": "seed", "narrative_id": narrative_id})
            fetch_jobs += 1
    return ImportResult(narratives, fetch_jobs)


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--file", type=Path, required=True, help="the feed's data.json")
    parser.add_argument("--since", type=date.fromisoformat, default=DEFAULT_SINCE, help="YYYY-MM-DD")
    parser.add_argument("--limit", type=int, help="import at most N claims, newest in file order")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO)

    claims, funnel = select_claims(feed_items(args.file), args.since)
    for step, count in funnel.items():
        print(f"{step}: {count}")
    claims = claims[: args.limit] if args.limit is not None else claims
    checkers = Counter(claim.fact_checker for claim in claims).most_common()
    print("fact-checkers:", ", ".join(f"{name} ({count})" for name, count in checkers))
    migrate()
    with connection() as conn:
        result = import_claims(conn, claims)
    print(f"{len(claims)} claims: {result.narratives} new narratives, {result.fetch_jobs} fetch jobs")


if __name__ == "__main__":
    main()
